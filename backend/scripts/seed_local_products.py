def main() -> None:
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    created = 0
    try:
        for p in PRODUCTS:
            exists = conn.execute(
                "SELECT id FROM local_product WHERE name = ? LIMIT 1", (p["name"],)
            ).fetchone()
            if exists is not None:
                continue
            now = services.now_iso()
            conn.execute(
                """
                INSERT INTO local_product(
                    name, subtitle, cover_url, detail_img_url, history, craft, flavor,
                    sort_order, created_at, updated_at
                )
                VALUES(?, ?, '', '', ?, ?, ?, ?, ?, ?)
                """,
                (p["name"], p["subtitle"], p["history"], p["craft"], p["flavor"], p["sort_order"], now, now),
            )
            created += 1
        conn.commit()
    finally:
        conn.close()
    print(f"好物初始化完成：新增 {created} 条（图片留空，待后台上传）。")


if __name__ == "__main__":
    main()
